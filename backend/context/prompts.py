def build_instructions(product: dict) -> str:
    """按固定顺序拼接销售规则和会话创建时的产品档案。

    Args:
        product: 已固定版本的产品字段，不包含上传文档或向量。

    Returns:
        写入 session.instructions 的完整字符串。
    """
    return SALES_RULES + json.dumps(product, ensure_ascii=False)
